class TestCommitMsgHook(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.base = Path(self.tmp.name)

    def tearDown(self):
        self.tmp.cleanup()

    def hook(self, root: Path, subject: str) -> int:
        message = self.base / "MSG"
        message.write_text(f"# comment\n{subject}\n\nbody\n")
        return subprocess.run([str(root / ".githooks/commit-msg"), str(message)], capture_output=True).returncode

    @unittest.skipIf(os.name == "nt", "executes the commit-msg hook through its #!/bin/sh line, which needs POSIX")
    def test_conventional_subjects(self):
        root = make_team_repo(self.base / "c")
        run_cli(root, "team", "init")
        for subject in ("feat: add login", "fix(api)!: drop v1", "chore(deps): bump", "Merge branch 'x'",
                        "fixup! feat: add login", 'Revert "feat: add login"'):
            with self.subTest(subject):
                self.assertEqual(0, self.hook(root, subject))
        for subject in ("add login", "feature: add login", "feat:", "Feat: add"):
            with self.subTest(subject):
                self.assertEqual(1, self.hook(root, subject))

    @unittest.skipIf(os.name == "nt", "executes the commit-msg hook through its #!/bin/sh line, which needs POSIX")
    def test_none_convention_accepts_anything(self):
        root = make_team_repo(self.base / "n", team=TEAM.format(host="github").replace(
            "team:\n", "team:\n  commit_convention: none\n"))
        run_cli(root, "team", "init")
        self.assertEqual(0, self.hook(root, "whatever"))

    def test_shim_in_active_hooks_dir(self):
        root = make_team_repo(self.base / "s")
        self.assertEqual(2, run_cli(root, "team", "hooks").returncode)
        run_cli(root, "team", "init")
        git(root, "config", "core.hooksPath", ".beads/hooks")
        installed = run_cli(root, "team", "hooks")
        self.assertEqual(0, installed.returncode, installed.stderr)
        self.assertTrue(installed.stdout.startswith("installed: "))
        git(root, "add", "-A")
        bad = subprocess.run(["git", "commit", "-q", "-m", "no convention"], cwd=root, capture_output=True, text=True)
        self.assertNotEqual(0, bad.returncode)
        self.assertIn("Conventional Commits", bad.stderr)
        good = subprocess.run(["git", "commit", "-q", "-m", "chore: init"], cwd=root, capture_output=True, text=True,
                              env={**os.environ})
        self.assertEqual(0, good.returncode, good.stderr)
        write(root, ".beads/hooks/commit-msg", "#!/bin/sh\nexit 0\n")
        self.assertEqual(1, run_cli(root, "team", "hooks").returncode)
        git(root, "config", "core.hooksPath", ".githooks")
        self.assertTrue(run_cli(root, "team", "hooks").stdout.startswith("active: "))


class TestSingleHolderNotes(unittest.TestCase):
    """approval-roles R6: doctor names gate `all` roles and area leads that only one member holds."""

    @staticmethod
    def _team(*extra_members):
        members = {
            "lan@x.com": {"roles": ["pm"], "login": "lan"},
            "an@x.com": {"roles": ["ba"], "login": "an"},
            "binh@x.com": {"roles": ["be_lead"], "login": "binh"},
            "em@x.com": {"roles": ["be_dev"], "login": "em"},
            "dung@x.com": {"roles": ["be_dev"], "login": "dung"},
            "hoa@x.com": {"roles": ["fe_lead", "fe_dev"], "login": "hoa"},
            "chi@x.com": {"roles": ["qe"], "login": "chi"},
        }
        for email in extra_members:
            members[email] = {"roles": ["qe"], "login": email.split("@")[0]}
        return load_team({"team": {
            "members": members,
            "areas": {"api": {"paths": ["services/**"], "lead": "be_lead", "roles": ["be_dev"]},
                      "web": {"paths": ["apps/**"], "lead": "fe_lead", "roles": ["fe_dev"]}},
            "approvals": {"ship": {"all": ["qe"], "any": ["be_lead", "fe_lead"]}, "plan_approved": "area_lead"},
        }})

    def test_doctor_notes_single_holders(self):
        notes = single_holder_notes(self._team())
        self.assertIn("ship: qe has one holder (chi)", notes)
        self.assertIn("area api: lead be_lead has one holder (binh)", notes)
        self.assertIn("area web: lead fe_lead has one holder (hoa)", notes)
        self.assertFalse([note for note in notes if note.startswith("ship: be_lead")])

    def test_second_holder_removes_the_note(self):
        notes = single_holder_notes(self._team("qe2@x.com"))
        self.assertFalse([note for note in notes if note.startswith("ship:")])

    def test_per_kind_policy_notes_name_the_kind(self):
        team = replace(self._team(), approvals={"requirement_confirmed": {"capability": {"all": ["ba"]},
                                                                          "technical": {"all": ["pm"]}}})
        notes = single_holder_notes(team)
        self.assertIn("requirement_confirmed.capability: ba has one holder (an)", notes)
        self.assertIn("requirement_confirmed.technical: pm has one holder (lan)", notes)


