"""`gin team init`: CODEOWNERS, PR/MR template, commit-msg hook, and optional CI per host."""

from __future__ import annotations

import fnmatch
from pathlib import Path
import subprocess
from typing import Any, Mapping

from .atomic import atomic_write_many
from .executables import tool
from .hosts import adapter
from .specs import render, sdd_config, template_text
from .team import POLICY_GATES, TeamConfig, TeamError, policy_entries, policy_roles

MARKER = "generated by gin team init"
LEGACY_MARKER = "generated by gin-workflow team init"


def _ours(text: str) -> bool:
    return MARKER in text or LEGACY_MARKER in text


HOOK = ".githooks/commit-msg"


def codeowners_path(team: TeamConfig) -> str | None:
    """The host's CODEOWNERS path; None when the host has none."""
    return adapter(team.host).files.codeowners


def _logins(team: TeamConfig, roles: set[str]) -> list[str]:
    return sorted(f"@{member.login}" for member in team.members.values() if roles & set(member.roles))


def reroot(glob: str, child: str) -> str | None:
    """Re-root an area glob into the child at path `child`."""
    glob_segs = [s for s in glob.strip("/").split("/") if s]
    child_segs = [s for s in child.strip("/").split("/") if s]
    for i, c_seg in enumerate(child_segs):
        if i >= len(glob_segs):
            return None
        g_seg = glob_segs[i]
        if g_seg == "**":
            return "/**"
        if not fnmatch.fnmatchcase(c_seg, g_seg):
            return None
    remaining = glob_segs[len(child_segs):]
    if not remaining:
        return "/**"
    return "/" + "/".join(remaining)


def codeowners(team: TeamConfig, config: Mapping[str, Any], child: str | None = None) -> str | None:
    """Area globs owned by the area lead; plan and spec folders owned by the approvers of those gates."""
    lines = [f"# {MARKER}; edit team: in .agent-workflow/config.yaml and rerun", ""]
    leads = {area.lead for area in team.areas.values()}
    if child is not None:
        area_lines = []
        for area in team.areas.values():
            owners = _logins(team, {area.lead})
            for glob in area.paths:
                rerooted = reroot(glob, child)
                if rerooted is not None:
                    area_lines.append(f"{rerooted} {' '.join(owners)}")
        if not area_lines:
            return None
        return "\n".join(lines + area_lines) + "\n"
    for area in team.areas.values():
        owners = _logins(team, {area.lead})
        lines += [f"/{glob} {' '.join(owners)}" for glob in area.paths]
    artifacts = config.get("artifacts") if isinstance(config.get("artifacts"), Mapping) else {}
    cfg = sdd_config(config)
    spec_dirs = [cfg["specs"], cfg["changes"]] if cfg["layout"] == "sdd" else [".planning/specs"]
    kinds = policy_entries("requirement_confirmed", team.approvals.get("requirement_confirmed", []))
    spec_roles = set().union(*(policy_roles(policy, team) for _, policy in kinds)) | leads
    for directory, roles in ([(artifacts.get("plans", ".planning/plans"), leads)]
                             + [(directory, spec_roles) for directory in spec_dirs]):
        owners = _logins(team, roles)
        if owners:
            lines.append(f"/{str(directory).strip('/')}/ {' '.join(owners)}")
    return "\n".join(lines) + "\n"


def planned_files(root: Path, team: TeamConfig, config: Mapping[str, Any], *, ci: bool,
                  child: str | None = None,
                  template_root: Path | None = None) -> dict[str, str]:
    host = adapter(team.host)
    names = host.files
    if ci and (names.ci is None or names.ci_template is None):
        raise TeamError(host.ci_unsupported or f"team.host {team.host} has no CI workflow file")
    values = {"convention": team.commit_convention}
    files: dict[str, str] = {}
    tpl_root = template_root or root
    if names.codeowners is not None:
        owners = codeowners(team, config, child=child)
        if owners is not None:
            files[names.codeowners] = owners
    if names.template is not None:
        files[names.template] = template_text(tpl_root, "team/pull_request_template.md")
    files[HOOK] = render(template_text(tpl_root, "team/commit-msg"), values)
    if ci:
        files[names.ci] = render(template_text(tpl_root, names.ci_template), values)
    return files


def init(root: Path, team: TeamConfig, config: Mapping[str, Any], *, ci: bool = False,
         force: bool = False, child: str | None = None,
         template_root: Path | None = None) -> dict[str, Any]:
    written, skipped, unchanged = [], [], []
    writes: dict[Path, bytes] = {}
    for relative, text in planned_files(root, team, config, ci=ci, child=child,
                                        template_root=template_root).items():
        path = Path(root) / relative
        if path.is_file():
            current = path.read_text(encoding="utf-8")
            if current == text:
                unchanged.append(relative)
                continue
            if not _ours(current) and not force:
                skipped.append(relative)
                continue
        writes[path] = text.encode("utf-8")
        written.append(relative)
    hook = Path(root) / HOOK
    if hook in writes:
        atomic_write_many({hook: writes.pop(hook)}, mode=0o755)
    if writes:
        atomic_write_many(writes, mode=0o644)
    return {"written": written, "skipped": skipped, "unchanged": unchanged}


def codeowners_drift(root: Path, team: TeamConfig, config: Mapping[str, Any]) -> bool:
    """True when the CODEOWNERS file is missing or stale; False on a host without one."""
    relative = codeowners_path(team)
    if relative is None:
        return False
    path = Path(root) / relative
    return not path.is_file() or path.read_text(encoding="utf-8") != codeowners(team, config)


SHIM = f"""#!/bin/sh
# {MARKER}: commit-msg shim
exec "$(git rev-parse --show-toplevel)/{HOOK}" "$@"
"""


def active_hooks_dir(root: Path) -> Path:
    listed = subprocess.run(["git", "rev-parse", "--git-path", "hooks"], cwd=root, text=True, capture_output=True,
                            check=True).stdout.strip()
    return (Path(root) / listed).resolve()


def hook_active(root: Path) -> bool:
    active = active_hooks_dir(root)
    if active == (Path(root) / ".githooks").resolve():
        return (active / "commit-msg").is_file()
    path = active / "commit-msg"
    return path.is_file() and _ours(path.read_text(encoding="utf-8", errors="replace"))


def install_hook(root: Path) -> dict[str, Any]:
    """Point the active hooks directory (often `.beads/hooks`) at `.githooks/commit-msg` without changing it."""
    if not (Path(root) / HOOK).is_file():
        return {"status": "missing", "path": HOOK}
    active = active_hooks_dir(root)
    if active == (Path(root) / ".githooks").resolve():
        return {"status": "active", "path": HOOK}
    target = active / "commit-msg"
    if target.is_file() and not _ours(target.read_text(encoding="utf-8", errors="replace")):
        return {"status": "occupied", "path": str(target)}
    active.mkdir(parents=True, exist_ok=True)
    atomic_write_many({target: SHIM.encode("utf-8")}, mode=0o755)
    return {"status": "installed", "path": str(target)}


def _ok(argv: list[str], root: Path) -> bool:
    executable = tool(argv[0], root)
    if executable is None:
        return False
    try:
        return subprocess.run([executable, *argv[1:]], cwd=root, capture_output=True, check=False,
                              timeout=30).returncode == 0
    except (OSError, subprocess.SubprocessError):
        return False


def gate_policy_gap(team: TeamConfig) -> list[str]:
    from .team import has_policy

    return [gate for gate in POLICY_GATES if not has_policy(gate, team)]


def single_holder_notes(team: TeamConfig) -> list[str]:
    """Gate `all` roles and area leads that exactly one member holds (that member's own PR cannot be approved)."""
    from .team import policy_parts

    def holders(role: str) -> list[str]:
        return sorted(member.login or member.email for member in team.members.values() if role in member.roles)

    notes = []
    for gate, gate_policy in sorted(team.approvals.items()):
        for name, policy in policy_entries(gate, gate_policy):
            for role in policy_parts(policy)[0]:
                found = holders(role)
                if len(found) == 1:
                    notes.append(f"{name}: {role} has one holder ({found[0]})")
    for name, area in sorted(team.areas.items()):
        found = holders(area.lead)
        if len(found) == 1:
            notes.append(f"area {name}: lead {area.lead} has one holder ({found[0]})")
    return notes


def doctor_report(root: Path, team: TeamConfig, config: Mapping[str, Any]) -> dict[str, Any]:
    """`setup doctor` section for team mode: every check plus one fix per failing check."""
    from .team import current_member, needs_pr

    host = adapter(team.host)
    extra = host.doctor_checks(root)
    checks: dict[str, bool] = {
        "member": current_member(root, team) is not None,
        "host_cli": _ok(host.auth_check_argv(root), root),
        **{name: ok for name, (ok, _) in extra.items()},
        "codeowners": not codeowners_drift(root, team, config),
        "gate_policy": not gate_policy_gap(team),
    }
    if team.commit_convention != "none":
        checks["hook"] = hook_active(root)
    if needs_pr("requirement_confirmed", team):
        checks["spec_review"] = sdd_config(config)["spec_review"] == "pr"
    if team.beads_remote:
        bd = tool("bd", root)
        listed = subprocess.run([bd, "dolt", "remote", "list"], cwd=root, text=True, capture_output=True,
                                check=False) if bd else None
        checks["beads_remote"] = bool(listed and team.beads_remote in listed.stdout)
        if team.beads_remote.startswith("git+"):
            checks["beads_remote"] = checks["beads_remote"] and _ok(
                ["git", "ls-remote", "--heads", team.beads_remote[4:]], root)
    fixes = {
        "member": "add your git user.email to team.members, or fix `git config user.email`",
        "host_cli": f"install {host.executable} and run `{host.login_fix}`",
        **{name: fix for name, (_, fix) in extra.items()},
        "codeowners": "run `gin team init` and commit the result",
        "gate_policy": "set team.approvals.<gate> to a role list or area_lead "
                       f"(gates without a policy: {', '.join(gate_policy_gap(team))})",
        "hook": "run `gin team init` then `gin team hooks`",
        "spec_review": "set artifacts.spec_review: pr (requirement_confirmed needs PR approval)",
        "beads_remote": f"run `bd dolt remote add origin {team.beads_remote}` and `gin team sync`",
    }
    report: dict[str, Any] = {"checks": checks, "actions": [fixes[name] for name, ok in checks.items() if not ok]}
    notes = host.doctor_notes() + single_holder_notes(team)
    if notes:
        report["note"] = "; ".join(notes)
    return report
