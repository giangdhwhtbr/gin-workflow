"""Git hooks that run the project's verify commands without an agent."""

from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import re
import subprocess
import sys
from typing import Any, Mapping, Sequence

from .atomic import atomic_write_many
from .configuration import resolve_effective_config
from .project import project_settings
from .team_init import active_hooks_dir
from . import verification, workspace

MARKER = "generated by gin hooks install"
LEGACY_MARKER = "generated by gin-workflow hooks install"
_RUN, _LEGACY_RUN = "gin hooks run", "gin-workflow hooks run"
HOOKS = ("pre-commit", "pre-push")
_PRE_COMMIT = ("lint", "typecheck")
_PRE_PUSH = {"easy": ("test",), "standard": ("test", "build"), "strict": ("test", "build", "e2e")}
# git opens the SSH connection before pre-push runs; a long test run lets the
# server drop it as idle and the push dies with SIGPIPE (exit 141).
SSH_KEEPALIVE = "ssh -o ServerAliveInterval=30"
_GIT_ENV = ("GIT_DIR", "GIT_WORK_TREE", "GIT_INDEX_FILE", "GIT_PREFIX", "GIT_OBJECT_DIRECTORY", "GIT_COMMON_DIR")


def _shim(hook: str) -> str:
    return (f"#!/bin/sh\n# {MARKER}: {hook}\n"
            'command -v gin >/dev/null 2>&1 || '
            '{ echo "gin is not on PATH; run ./install.sh" >&2; exit 1; }\n'
            f'exec gin hooks run {hook} "$@"\n')


def _ours(text: str) -> bool:
    return MARKER in text or LEGACY_MARKER in text


def install(root: Path) -> dict:
    active = active_hooks_dir(Path(root))
    if not active.is_dir():
        return {"status": "missing", "path": str(active), "hooks": {}}
    result: dict[str, str] = {}
    for hook in HOOKS:
        target, content = active / hook, _shim(hook)
        current = target.read_text(encoding="utf-8", errors="replace") if target.is_file() else None
        if current is not None and not _ours(current):
            result[hook] = "chained" if _RUN in current or _LEGACY_RUN in current else "occupied"
        elif current == content:
            result[hook] = "unchanged"
        else:
            atomic_write_many({target: content.encode("utf-8")}, mode=0o755)
            result[hook] = "installed"
    return {"status": "occupied" if "occupied" in result.values() else "installed",
            "path": str(active), "hooks": result, "ssh_keepalive": _keep_ssh_alive(Path(root))}


def _keep_ssh_alive(root: Path) -> str:
    """Set a repo-local core.sshCommand with a keepalive unless the user already chose one."""
    configured = subprocess.run(["git", "config", "core.sshCommand"], cwd=root, capture_output=True).stdout.strip()
    if configured or os.environ.get("GIT_SSH") or os.environ.get("GIT_SSH_COMMAND"):
        return "kept"
    written = subprocess.run(["git", "config", "--local", "core.sshCommand", SSH_KEEPALIVE], cwd=root,
                             capture_output=True)
    return "set" if written.returncode == 0 else "failed"


def status(root: Path) -> dict[str, str]:
    active, out = active_hooks_dir(Path(root)), {}
    for hook in HOOKS:
        target = active / hook
        if not target.is_file():
            out[hook] = "missing"
        else:
            text = target.read_text(encoding="utf-8", errors="replace")
            if MARKER in text or _RUN in text:
                out[hook] = "ok"
            elif LEGACY_MARKER in text or _LEGACY_RUN in text:
                out[hook] = "stale"
            else:
                out[hook] = "occupied"
    return out


def _scoped(root: Path, hook: str | None) -> tuple[list[tuple[Path, list[tuple[str, str]]]], Path, str]:
    """(cwd, [(name, command)]) groups for `hook` (every check when None), the events root, and the rigor."""
    located = workspace.locate(Path(root))
    settings = project_settings(resolve_effective_config(located.root, write=False).config.to_dict())
    if hook is None:
        names: tuple[str, ...] = workspace.CHECK_NAMES
    else:
        names = _PRE_PUSH.get(settings.rigor, _PRE_PUSH["standard"]) if hook == "pre-push" else _PRE_COMMIT
    if located.entry is not None:
        checks = located.entry.checks
        return ([(Path(root), [(f"{located.entry.path}:{name}", checks[name]) for name in names if checks.get(name)])],
                located.root, settings.rigor)
    scoped = [(root, [(name, settings.verify_commands[name]) for name in names if settings.verify_commands.get(name)])]
    for package in settings.packages:
        checks = (package.get("verify") or {}).get("checks") or {}
        scoped.append((root / package["path"],
                       [(f"{package['path']}:{name}", checks[name]) for name in names if checks.get(name)]))
    return scoped, root, settings.rigor


def status_report(root: Path) -> dict[str, Any]:
    """What `ship` checks: every hook installed and at least one verify command to run."""
    scoped, _, _ = _scoped(Path(root), None)
    hooks = status(root)
    names = sorted(name for _, commands in scoped for name, _ in commands)
    return {"hooks": hooks, "verify_commands": names, "ok": all(state == "ok" for state in hooks.values()) and bool(names)}


def _pushes_head(root: Path, refs: Sequence[str]) -> bool:
    """True when a pushed ref is a non-delete branch (or `HEAD` pushed to a branch) whose local sha is the checked-out HEAD."""
    head = subprocess.run(["git", "rev-parse", "HEAD"], cwd=root, text=True, capture_output=True,
                          check=False).stdout.strip()
    for line in refs:
        parts = line.split()
        if len(parts) == 4 and (parts[0] if parts[0] != "HEAD" else parts[2]).startswith("refs/heads/") and parts[1] == head and set(parts[1]) != {"0"}:
            return True
    return False


_ENV_PREFIX = re.compile(r"^([A-Za-z_][A-Za-z0-9_]*)=([^\s\"'$`;|&<>()\\]*)\s+")


def _split_env_prefix(command: str) -> tuple[str, dict[str, str]]:
    """Leading NAME=value words become environment variables, as a POSIX shell would do."""
    prefix: dict[str, str] = {}
    while (match := _ENV_PREFIX.match(command)):
        prefix[match.group(1)] = match.group(2)
        command = command[match.end():]
    return command, prefix


def _run_commands(hook: str, commands: Sequence[tuple[str, str]], cwd: Path, env: Mapping[str, str]) -> int:
    for name, command in commands:
        print(f"gin {hook}: {name}: {command}", file=sys.stderr)
        shell_command, prefix = _split_env_prefix(command)
        code = subprocess.run(shell_command, shell=True, cwd=cwd, env={**env, **prefix}).returncode
        if code != 0:
            print(f"gin {hook}: {name} failed (exit {code})", file=sys.stderr)
            return code
    return 0


def run(root: Path, hook: str, refs: Sequence[str] = ()) -> int:
    root = Path(root)
    if hook == "pre-push" and not _pushes_head(root, refs):
        print("gin: pre-push tested nothing (no pushed branch at the checked-out HEAD)", file=sys.stderr)
        return 0
    return verify(root, hook)


def verify(root: Path, hook: str) -> int:
    """Run the hook's verify commands; a passing pre-push on a clean tree is recorded."""
    root = Path(root)
    scoped, events_root, _ = _scoped(root, hook)
    if not any(commands for _, commands in scoped):
        print(f"gin: no verify commands configured for {hook}; nothing to run", file=sys.stderr)
        return 0
    # Taken before the commands run, so the record names the tree they tested.
    tree = verification.clean_tree(root) if hook == "pre-push" else None
    if tree:
        try:
            proven, _ = verification.check(root, "HEAD", events_root=events_root)
        except Exception as error:  # an unreadable record file never blocks the hook; the commands run
            print(f"gin {hook}: earlier runs not readable: {error}", file=sys.stderr)
            proven = None
        expected = {name for _, commands in scoped for name, _ in commands}
        if proven and expected <= set(proven["commands"]):
            print(f"gin {hook}: {', '.join(sorted(expected))} already passed on this tree "
                  f"(recorded {proven['recorded_at']}); nothing to rerun", file=sys.stderr)
            return 0
    env = {key: value for key, value in os.environ.items() if key not in _GIT_ENV}
    for cwd, commands in scoped:
        code = _run_commands(hook, commands, cwd, env)
        if code:
            return code
    if tree:
        try:
            verification.record(root, hook, tree, [name for _, commands in scoped for name, _ in commands],
                                events_root=events_root)
        except Exception as error:  # a failed record never changes the hook's result
            print(f"gin {hook}: passing run not recorded: {error}", file=sys.stderr)
    return 0


def _install_all(root: Path) -> int:
    space = workspace.locate(root).workspace
    if space is None:
        print("error: not in a workspace", file=sys.stderr)
        return 1
    for repo in space.repos:
        if repo.frozen:
            print(f"{repo.path}: skipped (frozen)")
        elif not repo.workable:
            print(f"{repo.path}: skipped ({repo.shape})")
        elif not space.present(repo):
            print(f"{repo.path}: skipped (not cloned)")
        else:
            for hook, state in install(space.checkout(repo))["hooks"].items():
                print(f"{repo.path}: {hook}: {state}")
    return 0


def main(argv: Sequence[str]) -> int:
    parser = argparse.ArgumentParser(prog="gin hooks")
    parser.add_argument("action", choices=("install", "run", "status"))
    parser.add_argument("hook", nargs="?", choices=HOOKS)
    parser.add_argument("git_args", nargs="*", help="arguments git passes to the hook (pre-push: remote name and URL); ignored")
    parser.add_argument("--repository", type=Path, default=None)
    parser.add_argument("--all-repos", action="store_true", help="install: every workable cloned repository of the workspace")
    args = parser.parse_args(list(argv))
    root = args.repository.resolve() if args.repository else Path.cwd().resolve()
    if args.action == "status":
        report = status_report(root)
        print(json.dumps(report, indent=2, sort_keys=True))
        return 0 if report["ok"] else 1
    if args.action == "install" and args.all_repos:
        return _install_all(root)
    if args.action == "install":
        result = install(root)
        for hook, state in result["hooks"].items():
            print(f"{hook}: {state}")
        if result.get("ssh_keepalive") == "set":
            print(f"core.sshCommand: {SSH_KEEPALIVE} (keeps the push connection open while pre-push runs)")
        if result.get("ssh_keepalive") == "failed":
            print("could not set core.sshCommand; a long pre-push run may drop the push connection", file=sys.stderr)
        if result["status"] == "missing":
            print(f"hooks directory {result['path']} does not exist; create it or fix core.hooksPath", file=sys.stderr)
        if result["status"] == "occupied":
            print('add `exec gin hooks run <hook> "$@"` to the existing hook to chain it', file=sys.stderr)
        return {"installed": 0, "occupied": 1, "missing": 2}[result["status"]]
    if args.hook is None:
        parser.error("run needs a hook name")
    refs = sys.stdin.read().splitlines() if args.hook == "pre-push" and not sys.stdin.isatty() else []
    return run(root, args.hook, refs)
